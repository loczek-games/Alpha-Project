--[[
	SoundConfig (ModuleScript)
	Location: ReplicatedStorage/Config/SoundConfig

	THE single place for every sound in CAUGHT ON CAMERA.

	How a sound id is resolved (first match wins):
	  1. entry.Ids          - individual uploaded variations ("rbxassetid://123", ...)
	  2. SoundConfig.Loops  - a dedicated seamless loop file (looped entries only)
	  3. SoundConfig.Banks  - one uploaded "sound bank" file containing many sounds;
	                          regions come from SoundBankLayout (generated by
	                          tools/sfx/generate_sfx.py together with assets/audio/)
	  4. entry.Fallback     - a built-in Roblox sound, pitched, so NOTHING is silent
	                          even before you upload any audio.

	All original sounds of the game live in just FOUR files
	(assets/audio/banks/*.ogg): upload them, paste the 4 ids below, done.
	(Alternative without editing code: set the attributes SoundBank_Equipment,
	SoundBank_Player, SoundBank_World and SoundBank_Loops on SoundService in
	Studio to the uploaded ids - they override the table below.)

	Every asset is preloaded with ContentProvider and verified at runtime; a
	missing or failed asset prints "[AudioService] Failed sound: <path>" and
	that sound falls back to the next source automatically. /soundtest (admin)
	and SETTINGS > AUDIO > TEST SOUND check the whole chain.

	Every entry is addressed by its path, e.g. "Camera.Shutter",
	"Flashlight.On", "EMF.Level5", "Player.Footstep.Metal",
	"Door.Security.Slam", "Anomaly.ListenerAttack".

	Entry fields
	  Ids           { "rbxassetid://..." }  explicit variations (optional)
	  Volume        base volume
	  Pitch         { min, max } random PlaybackSpeed multiplier (subtle variation)
	  VolumeJitter  +/- fraction of random volume variation
	  Group         SoundGroup: Music, Ambience, PlayerSFX, EquipmentSFX, AnomalySFX, Voice, Jumpscares, UI
	  Spatial       true = 3D positional (heard from its position), false = 2D
	  RollOff       { RollOffMinDistance, RollOffMaxDistance }
	  Occlusion     muffle when walls are between the listener and the sound
	  Noise         world noise intensity (0-1) when a PLAYER makes this sound
	  NoiseKind     what sound-sensitive anomalies "hear" (Shutter, Flash, Run, DoorSlam, ...)
	  Looped        loops until stopped
	  Fallback      { builtinId, playbackSpeed }
]]


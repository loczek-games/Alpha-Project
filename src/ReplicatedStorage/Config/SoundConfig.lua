local CATEGORIES = { "Camera", "Flashlight", "EMF", "Thermal", "UV", "NightVision", "Equipment", "Player", "Door", "Interaction", "Anomaly", "Jumpscare", "Environment", "Ambience", "Music", "UI" }
SoundConfig.Categories = CATEGORIES

local byPath = {}

local function register(prefix: string, node)
	for key, value in pairs(node) do
		if type(value) == "table" then
			local path = prefix .. "." .. key
			if value.Group ~= nil and value.Volume ~= nil then
				value.Path = path
				byPath[path] = value
			else
				register(path, value)
			end
		end
	end
end

for _, category in ipairs(CATEGORIES) do
	register(category, SoundConfig[category])
end

function SoundConfig.Get(path: string)
	return byPath[path]
end

function SoundConfig.AllPaths(): { string }
	local list = {}
	for path in pairs(byPath) do
		table.insert(list, path)
	end
	table.sort(list)
	return list
end

return SoundConfig

local function S(entry)
	entry.Ids = entry.Ids or {}
	entry.Volume = entry.Volume or 0.7
	entry.Pitch = entry.Pitch or { 0.96, 1.04 }
	entry.VolumeJitter = entry.VolumeJitter or 0.08
	entry.Group = entry.Group or "EquipmentSFX"
	if entry.Spatial == nil then
		entry.Spatial = true
	end
	entry.RollOff = entry.RollOff or { 6, 70 }
	if entry.Occlusion == nil then
		entry.Occlusion = entry.Spatial
	end
	return entry
end

